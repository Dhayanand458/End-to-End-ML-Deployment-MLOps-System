import pandas as pd
import streamlit as st
from utils import get_latest_paths, load_json

st.title("Data Quality (Great Expectations)")
paths = get_latest_paths()
sumj = load_json(paths["ge_summary"]) if paths["ge_summary"].exists() else {}

col1, col2 = st.columns([1, 3])
with col1:
    st.metric("BLOCKERS", sumj.get("blockers", 0))
    st.metric("WARNINGS", sumj.get("warns", 0))
with col2:
    st.write("**Expectation results**")
    rows = sumj.get("results", [])
    if rows:
        df = pd.DataFrame(
            [
                {
                    "expectation": r.get("type"),
                    "success": r.get("success"),
                    **{
                        k: v
                        for k, v in (r.get("kwargs") or {}).items()
                        if not isinstance(v, list | dict)
                    },
                }
                for r in rows
            ]
        )
        st.dataframe(df, use_container_width=True, hide_index=True)
    else:
        st.info("No GE summary found. Run dq_validate.py first.")

st.divider()
if paths["ge_summary"].exists():
    st.caption("Raw summary JSON")
    st.code(paths["ge_summary"].read_text()[:4000])

st.divider()
st.subheader("Open full Data Docs")
st.caption("Open the HTML site generated by GE (index.html under the same folder).")
